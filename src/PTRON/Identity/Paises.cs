    private static readonly Dictionary<string, Pais> ByCode =
        All.ToDictionary(p => p.Codigo, StringComparer.OrdinalIgnoreCase);

    private static readonly Dictionary<string, IReadOnlyList<Pais>> SortedByLanguage = new();

    public static IReadOnlyList<Pais> Todos
    {
        get
        {
            var culture = CultureInfo.CurrentUICulture;
            var key = culture.TwoLetterISOLanguageName is "en" or "es" ? culture.TwoLetterISOLanguageName : "pt";
            lock (SortedByLanguage)
            {
                if (!SortedByLanguage.TryGetValue(key, out var list))
                {
                    list = key == "pt"
                        ? All
                        : All
                            .OrderBy(p => p.Codigo == "BR" ? 0 : 1)
                            .ThenBy(p => SortKey(key == "en" ? p.NomeEn : p.NomeEs), StringComparer.Ordinal)
                            .ToArray();
                    SortedByLanguage[key] = list;
                }

                return list;
            }
        }
    }

    private static string SortKey(string name)
    {
        var decomposed = name.Normalize(System.Text.NormalizationForm.FormD);
        var chars = decomposed.Where(c => CharUnicodeInfo.GetUnicodeCategory(c) != UnicodeCategory.NonSpacingMark);
        return new string(chars.ToArray()).ToUpperInvariant();
    }

    public static bool IsValid(string? codigo) => !string.IsNullOrWhiteSpace(codigo) && ByCode.ContainsKey(codigo.Trim());

    public static string? Nome(string? codigo)
        => !string.IsNullOrWhiteSpace(codigo) && ByCode.TryGetValue(codigo.Trim(), out var pais) ? pais.Nome : null;
}
